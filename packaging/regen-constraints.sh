#!/usr/bin/env bash
# Regenerate packaging/constraints.txt from packaging/requirements.txt.
#
# The bundle installs in two resolves, and constraints.txt has to be valid for both:
#   1. the engine step, `uv pip install -r requirements.txt`, where package-thin adds the PyTorch
#      CPU index AHEAD of PyPI (uv's first-index rule: a package that index carries is taken
#      only from it);
#   2. the by-path step, which installs the tooling wheel and the huggingface_hub wheel with no
#      PyTorch index, so everything it needs resolves from PyPI.
# So this script resolves step 1 the way uv will (same index order), then resolves the full set
# with step 1's pins fixed, adding huggingface_hub from PyPI.
#
# Usage: packaging/regen-constraints.sh        (needs network; rewrites constraints.txt)
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HF_HUB_VERSION="0.36.2"   # must equal HF_HUB_VERSION in package-thin.sh (a test checks)
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT

# ttnn's wheel tag is manylinux_2_34, so resolve for that platform.
COMMON=(--python-version 3.12 --python-platform x86_64-manylinux_2_34
        --extra-index-url https://download.pytorch.org/whl/cpu --no-header --no-annotate -q)

# Resolve 1: the engine step, with uv's default (first-index) strategy.
uv pip compile "$HERE/requirements.txt" "${COMMON[@]}" -o "$TMP/step1.txt"
# A direct-URL requirement prints as `name @ url`; a constraints file wants `name==version`.
VERSION_OF_URL() { sed -n "s#^$1 @ .*/$1-\([0-9.]*\)-py3.*#\1#p" "$TMP/step1.txt"; }
IDNA="$(VERSION_OF_URL idna)"
grep -v '^idna @' "$TMP/step1.txt" > "$TMP/step1-pins.txt"
echo "idna==$IDNA" >> "$TMP/step1-pins.txt"

# Resolve 2: everything, with resolve 1's pins fixed and PyPI allowed for what is new.
echo "huggingface_hub==$HF_HUB_VERSION" > "$TMP/extra.txt"
uv pip compile "$HERE/requirements.txt" "$TMP/extra.txt" "${COMMON[@]}" \
  --index-strategy unsafe-best-match -c "$TMP/step1-pins.txt" -o "$TMP/all.txt"

{
  cat <<EOF
# Fully resolved pins for every install step of the tt-vjepa2 bundle (--constraints).
# Generated by packaging/regen-constraints.sh on $(date +%F); do not edit by hand.
# Without a constraints file the engine step can take certifi, urllib3 and requests from the
# PyTorch CPU index, at one years-old version each, and install them silently. With this file,
# that case fails the install instead.
EOF
  sed "s#^idna @ .*#idna==$IDNA#" "$TMP/all.txt"
} > "$HERE/constraints.txt"
echo "wrote $HERE/constraints.txt ($(grep -c '==' "$HERE/constraints.txt") pins)"
